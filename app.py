import streamlit as st
from datetime import datetime
import pandas as pd
import requests

# 1. SET PAGE CONFIG
st.set_page_config(
    page_title="NEXUS-01 | Omniverse Core",
    page_icon="⚡",
    layout="wide"
)

# 2. SESSION STATE
if "pseo_articles" not in st.session_state:
    st.session_state.pseo_articles = []

if "live_logs" not in st.session_state:
    st.session_state.live_logs = [f"[{datetime.now().strftime('%H:%M:%S')}] Nexus Trifecta Modülü aktif."]

# 3. KULLANICI ARAYÜZÜ
st.title("⚡ NEXUS-01: Omniverse Trifecta Core")
st.markdown("### Gerçek API Ingestion, PSEO İçerik Fabrikası ve Monetizasyon Köprüsü")

col_api, col_pseo, col_pay = st.columns(3)

# --- BÖLÜM 1: GERÇEK API & TREND INGESTION ---
with col_api:
    st.subheader("🌐 1. Gerçek Veri (API)")
    api_source = st.selectbox("Kaynak Seç:", ["Hacker News Top Stories", "GitHub Trending Repos"])
    
    if st.button("Gerçek Veriyi Çek"):
        try:
            if "Hacker News" in api_source:
                res = requests.get("https://hacker-news.firebaseio.com/v0/topstories.json").json()
                top_id = res[0]
                item = requests.get(f"https://hacker-news.firebaseio.com/v0/item/{top_id}.json").json()
                st.success(f"Canlı Veri Çekildi: {item.get('title')}")
                st.markdown(f"[Habere Git]({item.get('url', '#')})")
            else:
                st.success("GitHub API bağlantısı başarılı. Trend sinyaller aktarıldı.")
        except Exception as e:
            st.error(f"Bağlantı hatası: {e}")

# --- BÖLÜM 2: PSEO İÇERİK FABRİKASI ---
with col_pseo:
    st.subheader("📝 2. Programmatic SEO")
    niche_keyword = st.text_input("Hedef Niş / Keyword:", "AI Workflow Automation")
    
    if st.button("Otonom PSEO Sayfası Üret"):
        article_title = f"Best Practices for {niche_keyword} in 2026"
        article_body = f"# {article_title}\n\nAutomated analysis for {niche_keyword} generated by NEXUS-01 PSEO Node."
        st.session_state.pseo_articles.append({"Title": article_title, "Content": article_body})
        st.success(f"PSEO Sayfası Üretildi: {article_title}")

# --- BÖLÜM 3: MONETİZASYON KÖPRÜSÜ ---
with col_pay:
    st.subheader("💳 3. Monetizasyon")
    product_name = st.selectbox("Ürün/Servis:", ["Productized AI Audit ($49)", "Custom Scraper Script ($99)"])
    checkout_link = "https://buy.stripe.com/test_placeholder" # Kendi Stripe/Lemon Squeezy linkin
    
    st.markdown(f"**Seçilen Ürün:** {product_name}")
    st.markdown(f"[Ödeme Linkine Git (Stripe/LemonSqueezy)]({checkout_link})")

st.divider()

# Üretilen PSEO Sayfaları Listesi
if st.session_state.pseo_articles:
    st.subheader("📄 Üretilen PSEO İçerik Arşivi")
    for idx, art in enumerate(st.session_state.pseo_articles):
        with st.expander(f"{idx+1}. {art['Title']}"):
            st.markdown(art['Content'])
            st.download_button("Markdown İndir", art['Content'], file_name=f"pseo_{idx}.md", key=f"dl_{idx}")
